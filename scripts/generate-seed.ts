/**
 * Writes supabase/seed.sql from the starter catalogue in packages/shared/src/catalog.ts.
 * Run with `npm run db:seed:generate`, then `npx supabase db reset` to load it locally.
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import {
  ageBands,
  bestSellers,
  categories,
  deliveryAreas,
  deliveryFees,
  newArrivals,
  products,
  relatedProducts,
  appNewArrivals,
  type Product,
} from '../packages/shared/src/index';

type SqlValue = string | number | boolean | null | undefined | object;

function lit(value: SqlValue): string {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'number') return String(value);
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (typeof value === 'string') return `'${value.replaceAll("'", "''")}'`;
  return `${lit(JSON.stringify(value))}::jsonb`;
}

/** Starting stock for every sellable unit, so the local store can take orders. */
const STARTER_STOCK = 25;

const rows = (values: SqlValue[][]) => values.map((row) => `  (${row.map(lit).join(', ')})`).join(',\n');
const productId = (slug: string) => `(select id from public.products where slug = ${lit(slug)})`;

const slots: Record<string, Product[]> = {
  // Floating cards around the hero image on the home page.
  home_hero: ['vitamin-c-brightening-serum', 'whipped-shea-body-butter', 'velvet-matte-lip-colour', 'gentle-baby-wash-shampoo'].map(
    (slug) => products.find((p) => p.slug === slug)!,
  ),
  home_new_arrivals: newArrivals,
  home_best_sellers: bestSellers,
  product_related: relatedProducts,
  app_new_arrivals_beauty: appNewArrivals.beauty,
  app_new_arrivals_kids: appNewArrivals.kids,
};

const sql = `-- Generated by scripts/generate-seed.ts from packages/shared/src/catalog.ts. Do not edit by hand.
-- Starter catalogue and checkout configuration for local development.
-- Load it into a hosted project with: npx supabase db push --include-seed

insert into public.age_bands (id, label, stage, sort_order) values
${rows(ageBands.map((b, i) => [b.id, b.label, b.stage, i]))};

insert into public.categories (id, name, department, image_key, tint, kind, sort_order) values
${rows(categories.map((c, i) => [c.id, c.name, c.department, c.image, c.tint, c.kind, i]))};

insert into public.products (
  slug, name, brand, department, category_id, kids_filter, collection, price_ghs, was_price_ghs,
  badge, tag, summary, image_key, tint, kind, details
) values
${rows(
  products.map((p) => [
    p.slug,
    p.name,
    p.brand,
    p.department,
    p.category,
    p.kidsFilter,
    p.collection,
    p.price,
    p.was,
    p.badge,
    p.tag,
    p.summary,
    p.image,
    p.tint,
    p.kind,
    p.details,
  ]),
)};

insert into public.product_sizes (product_id, code, label, price_ghs, is_default, sort_order)
${products
  .flatMap((p) =>
    (p.sizes ?? []).map(
      (s, i) =>
        `select ${productId(p.slug)}, ${lit(s.id)}, ${lit(s.label)}, ${s.price}, ${lit(s.id === p.defaultSize)}, ${i}`,
    ),
  )
  .join('\nunion all\n')};

insert into public.product_age_bands (product_id, age_band_id)
${products
  .flatMap((p) => (p.ageBands ?? []).map((band) => `select ${productId(p.slug)}, ${lit(band)}`))
  .join('\nunion all\n')};

insert into public.merchandising_slots (slot, product_id, position)
${Object.entries(slots)
  .flatMap(([slot, list]) => list.map((p, i) => `select ${lit(slot)}, ${productId(p.slug)}, ${i}`))
  .join('\nunion all\n')};

insert into public.inventory_levels (product_id, size_code, on_hand)
${products
  .flatMap((p) =>
    (p.sizes?.length ? p.sizes.map((s) => s.id) : ['']).map(
      (code) => `select ${productId(p.slug)}, ${lit(code)}, ${STARTER_STOCK}`,
    ),
  )
  .join('\nunion all\n')};

-- Starter stock sits in one sample batch per unit; beauty and bath products get a sample expiry date.
insert into public.stock_batches (product_id, size_code, batch_code, expires_on, quantity, note)
select i.product_id, i.size_code, 'STARTER',
       case when p.department = 'beauty' or p.kids_filter = 'bath' then date '2028-12-31' end,
       i.on_hand, 'Sample starter stock'
from public.inventory_levels i join public.products p on p.id = i.product_id;

insert into public.stock_movements (product_id, size_code, batch_id, reason, quantity, sellable_change, note)
select b.product_id, b.size_code, b.id, 'opening', b.quantity, b.quantity, b.note from public.stock_batches b;

insert into public.delivery_areas (name, sort_order) values
${rows(deliveryAreas.map((name, i) => [name, i]))};

insert into public.delivery_options (id, label, fee_ghs, sort_order) values
${rows([
  ['standard', 'Standard', deliveryFees.standard, 0],
  ['same_day', 'Same day', deliveryFees.sameDay, 1],
])};
`;

const out = resolve(import.meta.dirname, '../supabase/seed.sql');
writeFileSync(out, sql);
console.log(`Wrote ${out}`);
