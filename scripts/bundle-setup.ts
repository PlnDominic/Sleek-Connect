/**
 * Writes supabase/setup.sql: every migration in order, then the reference data (no sample products), as one script for setting up a NEW Supabase
 * project by pasting it into the SQL Editor. Run with `npm run db:setup:generate` after adding a migration or
 * regenerating the seed. Existing projects should run only the migrations they haven't had yet.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '../supabase');
const migrations = readdirSync(resolve(root, 'migrations'))
  .filter((f) => f.endsWith('.sql'))
  .sort();

const parts = [
  `-- Sleek Connect Store: complete database setup for a NEW Supabase project.
-- Generated by \`npm run db:setup:generate\` from supabase/migrations/*.sql and supabase/seed.reference.sql. Don't edit by hand.
--
-- How to use: Supabase dashboard → SQL Editor → New query → paste this whole file → Run.
-- Only for an empty project. A project that already has some of these migrations needs just the newer files
-- from supabase/migrations, in order (or use \`npx supabase db push\`).
--
-- Contents:
${migrations.map((m) => `--   ${m}`).join('\n')}
--   seed.reference.sql (categories, age groups and delivery settings; no sample products)
`,
  ...migrations.map((m) => {
    const sql = readFileSync(resolve(root, 'migrations', m), 'utf8').trim();
    // A new enum value can't be used until the transaction that added it has committed. Applied one file at a time each
    // migration commits on its own; in this single script, end the transaction after a file that adds enum values.
    const commit = /alter\s+type\s+\S+\s+add\s+value/i.test(sql) ? '\n-- (new enum values: commit before the next file uses them)\ncommit;\n' : '';
    return `-- ===========================================================================\n-- ${m}\n-- ===========================================================================\n\n${sql}\n${commit}`;
  }),
  `-- ===========================================================================\n-- seed.reference.sql\n-- ===========================================================================\n\n${readFileSync(resolve(root, 'seed.reference.sql'), 'utf8').trim()}\n`,
];

const out = resolve(root, 'setup.sql');
writeFileSync(out, parts.join('\n'));
console.log(`Wrote ${out} (${migrations.length} migrations + reference data)`);
